export const getTranslation = (language: string, path: string): string => {
  const keys = path.split('.');
  let value: any = translations[language as keyof typeof translations] || translations.en;
  
  for (const key of keys) {
    value = value?.[key];
  }
  
  return typeof value === 'string' ? value : path;
};

export const t = (language: string, path: string): string => {
  return getTranslation(language, path);
};
